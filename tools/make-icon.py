#!/usr/bin/env python3
"""Generate the Nexify Player branding assets.

    python3 tools/make-icon.py [--preview-dir DIR]

Inputs (committed):
  assets/branding/nexify-mark.svg        the mark (tile + play triangle + slim chevron)
  assets/branding/nexify-mark-small.svg  heavier variant for the 16/24 px icon frames
  src/Nexify.App/Assets/Fonts/Archivo-Bold.ttf

Outputs (committed, so CI needs no Python):
  assets/branding/nexify-logo.svg        mark + "NEXIFY PLAYER" wordmark as outlined paths (light text, for dark backgrounds)
  assets/branding/nexify-logo-light.svg  same with dark text, for light backgrounds
  assets/branding/nexify-mark.png        256 px
  assets/branding/nexify.ico             16, 24, 32, 48, 64, 128, 256 px
  src/Nexify.App/Assets/nexify.ico       copy of the above (ApplicationIcon)
  src/Nexify.App/Assets/nexify-mark.png  copy of the 256 px PNG (for in-app use)

Requires: pip install cairosvg pillow fonttools uharfbuzz
"""
from __future__ import annotations

import argparse
import io
import re
import shutil
from pathlib import Path

import cairosvg
import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BRANDING = ROOT / "assets" / "branding"
APP_ASSETS = ROOT / "src" / "Nexify.App" / "Assets"
FONT = APP_ASSETS / "Fonts" / "Archivo-Bold.ttf"

ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
SMALL_SIZES = {16, 24}  # frames rendered from the small-size variant

WORDMARK = "NEXIFY PLAYER"
MARK_SIZE = 128          # mark drawn at 128x128 in the logo
GAP = 34                 # mark -> wordmark
CAP_HEIGHT = 46          # wordmark cap height in logo units
TRACKING = 0.02          # letter spacing as a fraction of the em
TEXT_DARK_BG = "#FFFFFF"
TEXT_LIGHT_BG = "#0A0C10"


def svg_inner(svg: str) -> str:
    """Return the children of the root <svg> element."""
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not m:
        raise ValueError("not an svg document")
    return m.group(1).strip()


def wordmark_path(text: str) -> tuple[str, float]:
    """Shape `text` with HarfBuzz (kerning) and return (svg path data, advance width) in logo units.

    The path's baseline sits at y=0 and caps reach y=-CAP_HEIGHT."""
    font = TTFont(FONT)
    upem = font["head"].unitsPerEm
    cap = font["OS/2"].sCapHeight
    scale = CAP_HEIGHT / cap

    blob = hb.Blob.from_file_path(str(FONT))
    hb_font = hb.Font(hb.Face(blob))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hb_font, buf, {"kern": True, "liga": False})

    glyph_set = font.getGlyphSet()
    order = font.getGlyphOrder()
    pen = SVGPathPen(glyph_set, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    x = 0.0
    tracking = TRACKING * upem
    infos, positions = buf.glyph_infos, buf.glyph_positions
    for i, (info, pos) in enumerate(zip(infos, positions)):
        name = order[info.codepoint]
        # font units -> logo units, flipping y (fonts are y-up, SVG is y-down)
        t = TransformPen(pen, (scale, 0, 0, -scale, (x + pos.x_offset) * scale, -pos.y_offset * scale))
        glyph_set[name].draw(t)
        x += pos.x_advance + (tracking if i < len(infos) - 1 else 0)
    # trim the right side bearing of the last glyph so the logo box ends at the ink
    last = order[infos[-1].codepoint]
    rsb = font["hmtx"][last][0] - font["glyf"][last].xMax if "glyf" in font else 0
    return pen.getCommands(), (x - max(rsb, 0)) * scale


def build_logo(mark_svg: str, text_color: str) -> str:
    path, width = wordmark_path(WORDMARK)
    s = MARK_SIZE / 256
    text_x = MARK_SIZE + GAP
    baseline = MARK_SIZE / 2 + CAP_HEIGHT / 2
    total_w = round(text_x + width + 1)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w} {MARK_SIZE}" '
        f'width="{total_w}" height="{MARK_SIZE}">\n'
        f'  <!-- Nexify Player logo. Generated by tools/make-icon.py; wordmark: Archivo Bold, outlined. -->\n'
        f'  <g transform="scale({s:g})">\n    {svg_inner(mark_svg)}\n  </g>\n'
        f'  <path transform="translate({text_x:g} {baseline:g})" fill="{text_color}" d="{path}"/>\n'
        f"</svg>\n"
    )


def render(svg: str, width: int, height: int | None = None) -> Image.Image:
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=width, output_height=height or width)
    return Image.open(io.BytesIO(png)).convert("RGBA")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview-dir", type=Path, help="also write inspection renders (logo PNGs, every icon size) here")
    args = ap.parse_args()

    mark = (BRANDING / "nexify-mark.svg").read_text(encoding="utf-8")
    mark_small = (BRANDING / "nexify-mark-small.svg").read_text(encoding="utf-8")

    logos = {
        "nexify-logo.svg": build_logo(mark, TEXT_DARK_BG),
        "nexify-logo-light.svg": build_logo(mark, TEXT_LIGHT_BG),
    }
    for name, svg in logos.items():
        (BRANDING / name).write_text(svg, encoding="utf-8", newline="\n")

    frames = {size: render(mark_small if size in SMALL_SIZES else mark, size) for size in ICO_SIZES}
    frames[256].save(BRANDING / "nexify-mark.png", optimize=True)
    ico = BRANDING / "nexify.ico"
    frames[256].save(ico, format="ICO", sizes=[(s, s) for s in ICO_SIZES],
                     append_images=[frames[s] for s in ICO_SIZES if s != 256])

    APP_ASSETS.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ico, APP_ASSETS / "nexify.ico")
    shutil.copyfile(BRANDING / "nexify-mark.png", APP_ASSETS / "nexify-mark.png")

    if args.preview_dir:
        out = args.preview_dir
        out.mkdir(parents=True, exist_ok=True)
        for size, im in frames.items():
            im.save(out / f"mark-{size}.png")
        for name, svg in logos.items():
            w = int(re.search(r'viewBox="0 0 (\d+)', svg).group(1))
            render(svg, w * 4, MARK_SIZE * 4).save(out / name.replace(".svg", ".png"))
            render(svg, w * 32 // MARK_SIZE, 32).save(out / name.replace(".svg", "-32.png"))
    print(f"wrote {ico} ({', '.join(map(str, ICO_SIZES))} px)")


if __name__ == "__main__":
    main()
